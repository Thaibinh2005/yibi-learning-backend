-- ============================================================
--  Yibi Platform — Flyway Migration V1
--  Script: V1__init_schema.sql
--  Description: Create all core tables for Yibi MVP
--  Tables: 12 tables covering Users, Content, SRS, Exam, Speech
-- ============================================================

-- Enable UUID extension (for gen_random_uuid())
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ──────────────────────────────────────────────────────────
--  1. USERS TABLE
--     Supports RBAC via role enum column.
--     hsk_level is NULL until Placement Test is completed.
-- ──────────────────────────────────────────────────────────
CREATE TABLE users (
    id              UUID            PRIMARY KEY DEFAULT gen_random_uuid(),
    username        VARCHAR(50)     NOT NULL,
    email           VARCHAR(100)    NOT NULL,
    password_hash   VARCHAR(255)    NOT NULL,
    role            VARCHAR(20)     NOT NULL DEFAULT 'ROLE_USER',
    is_active       BOOLEAN         NOT NULL DEFAULT TRUE,
    hsk_level       INTEGER,
    created_at      TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP       NOT NULL DEFAULT NOW(),
    last_login      TIMESTAMP,

    CONSTRAINT uq_users_username    UNIQUE (username),
    CONSTRAINT uq_users_email       UNIQUE (email),
    CONSTRAINT chk_users_role       CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN')),
    CONSTRAINT chk_users_hsk_level  CHECK (hsk_level IS NULL OR (hsk_level >= 1 AND hsk_level <= 9))
);

COMMENT ON TABLE  users                IS 'Platform users with RBAC role support';
COMMENT ON COLUMN users.role           IS 'ROLE_USER or ROLE_ADMIN — enforced in Spring Security';
COMMENT ON COLUMN users.hsk_level      IS 'Determined after Placement Test; NULL = not tested yet';

-- ──────────────────────────────────────────────────────────
--  2. VOCABULARY TABLE
--     Source: HSK 3.0 JSON import script (seed-data/).
--     audio_url is populated by Azure TTS → MinIO upload.
--     pinyin auto-generated by Pinyin4j on save.
--     hanzi_traditional auto-generated by OpenCC4j.
-- ──────────────────────────────────────────────────────────
CREATE TABLE vocabulary (
    id                  BIGSERIAL       PRIMARY KEY,
    hanzi               VARCHAR(20)     NOT NULL,
    hanzi_traditional   VARCHAR(20),
    pinyin              VARCHAR(100)    NOT NULL,
    meaning_vi          TEXT,
    meaning_en          TEXT,
    hsk_level           INTEGER         NOT NULL,
    part_of_speech      VARCHAR(50),
    example_sentence    TEXT,
    example_pinyin      TEXT,
    audio_url           VARCHAR(500),
    stroke_count        INTEGER,
    created_at          TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_vocab_hsk    CHECK (hsk_level >= 1 AND hsk_level <= 9)
);

CREATE INDEX idx_vocabulary_hsk_level ON vocabulary(hsk_level);
CREATE INDEX idx_vocabulary_hanzi     ON vocabulary(hanzi);

COMMENT ON COLUMN vocabulary.hanzi          IS '简体字 Simplified Chinese character(s)';
COMMENT ON COLUMN vocabulary.audio_url      IS 'MinIO URL of Azure TTS generated .mp3';
COMMENT ON COLUMN vocabulary.stroke_count   IS 'Used by hanzi-writer JS lib on frontend';

-- ──────────────────────────────────────────────────────────
--  3. GRAMMAR POINTS TABLE
--     examples: stored as JSONB array [{hanzi, pinyin, meaning}]
--     Data can be imported from LLM-generated JSON files.
-- ──────────────────────────────────────────────────────────
CREATE TABLE grammar_points (
    id          BIGSERIAL       PRIMARY KEY,
    title       VARCHAR(200)    NOT NULL,
    pattern     VARCHAR(300)    NOT NULL,
    explanation TEXT,
    examples    JSONB           NOT NULL DEFAULT '[]',
    hsk_level   INTEGER         NOT NULL,
    created_at  TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_grammar_hsk CHECK (hsk_level >= 1 AND hsk_level <= 9)
);

CREATE INDEX idx_grammar_hsk_level ON grammar_points(hsk_level);
CREATE INDEX idx_grammar_examples  ON grammar_points USING GIN (examples);

COMMENT ON COLUMN grammar_points.pattern  IS 'e.g. "Subject + 把 + Object + Verb"';
COMMENT ON COLUMN grammar_points.examples IS 'JSONB: [{hanzi, pinyin, meaning_vi, meaning_en}]';

-- ──────────────────────────────────────────────────────────
--  4. READING PASSAGES TABLE
-- ──────────────────────────────────────────────────────────
CREATE TABLE reading_passages (
    id              BIGSERIAL       PRIMARY KEY,
    title           VARCHAR(300)    NOT NULL,
    content_hanzi   TEXT            NOT NULL,
    content_pinyin  TEXT,
    translation_vi  TEXT,
    hsk_level       INTEGER         NOT NULL,
    word_count      INTEGER,
    created_at      TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_reading_hsk CHECK (hsk_level >= 1 AND hsk_level <= 9)
);

CREATE INDEX idx_reading_hsk_level ON reading_passages(hsk_level);

-- ──────────────────────────────────────────────────────────
--  5. COURSES TABLE
-- ──────────────────────────────────────────────────────────
CREATE TABLE courses (
    id              BIGSERIAL       PRIMARY KEY,
    title           VARCHAR(300)    NOT NULL,
    description     TEXT,
    hsk_level       INTEGER         NOT NULL,
    total_lessons   INTEGER         NOT NULL DEFAULT 0,
    created_at      TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_courses_hsk CHECK (hsk_level >= 1 AND hsk_level <= 9)
);

-- ──────────────────────────────────────────────────────────
--  6. LESSONS TABLE
--     content_ref_id is a polymorphic FK:
--     - VOCABULARY → vocabulary.id
--     - GRAMMAR    → grammar_points.id
--     - READING    → reading_passages.id
-- ──────────────────────────────────────────────────────────
CREATE TABLE lessons (
    id              BIGSERIAL       PRIMARY KEY,
    course_id       BIGINT          NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title           VARCHAR(300)    NOT NULL,
    lesson_order    INTEGER         NOT NULL DEFAULT 0,
    content_type    VARCHAR(20)     NOT NULL,
    content_ref_id  BIGINT,
    created_at      TIMESTAMP       NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_lesson_content_type CHECK (content_type IN ('VOCABULARY', 'GRAMMAR', 'READING', 'LISTENING'))
);

CREATE INDEX idx_lessons_course_id ON lessons(course_id);
CREATE INDEX idx_lessons_order     ON lessons(course_id, lesson_order);

-- ──────────────────────────────────────────────────────────
--  7. USER PROGRESS TABLE
--     Tracks per-user, per-lesson completion status.
-- ──────────────────────────────────────────────────────────
CREATE TABLE user_progress (
    id              BIGSERIAL       PRIMARY KEY,
    user_id         UUID            NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_id       BIGINT          NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    status          VARCHAR(20)     NOT NULL DEFAULT 'NOT_STARTED',
    score           DECIMAL(5, 2),
    completed_at    TIMESTAMP,

    CONSTRAINT uq_user_lesson           UNIQUE (user_id, lesson_id),
    CONSTRAINT chk_progress_status      CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE INDEX idx_user_progress_user_id   ON user_progress(user_id);
CREATE INDEX idx_user_progress_lesson_id ON user_progress(lesson_id);

-- ──────────────────────────────────────────────────────────
--  8. SRS CARDS TABLE — SM-2 Algorithm
--     ease_factor: EF — starts at 2.5, min 1.3
--     interval_days: I(n) — gap in days until next review
--     repetitions: n — number of successful reviews in a row
--     due_date: next scheduled review date (indexed for query)
-- ──────────────────────────────────────────────────────────
CREATE TABLE srs_cards (
    id              BIGSERIAL       PRIMARY KEY,
    user_id         UUID            NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vocabulary_id   BIGINT          NOT NULL REFERENCES vocabulary(id) ON DELETE CASCADE,
    ease_factor     DECIMAL(4, 2)   NOT NULL DEFAULT 2.50,
    interval_days   INTEGER         NOT NULL DEFAULT 1,
    repetitions     INTEGER         NOT NULL DEFAULT 0,
    due_date        DATE            NOT NULL DEFAULT CURRENT_DATE,
    last_reviewed   TIMESTAMP,

    CONSTRAINT uq_srs_user_vocab    UNIQUE (user_id, vocabulary_id),
    CONSTRAINT chk_ease_factor      CHECK (ease_factor >= 1.30)
);

-- Critical index: Query "show me cards due today for user X"
CREATE INDEX idx_srs_due ON srs_cards(user_id, due_date);

COMMENT ON TABLE  srs_cards             IS 'Spaced Repetition System cards using SM-2 algorithm';
COMMENT ON COLUMN srs_cards.ease_factor IS 'SM-2 EF: float 1.3-2.5+, higher = easier card';
COMMENT ON COLUMN srs_cards.due_date    IS 'Next review date; queried daily to build flashcard deck';

-- ──────────────────────────────────────────────────────────
--  9. LEARNING PATHS TABLE
--     One path per user (UNIQUE user_id).
--     Auto-generated after Placement Test.
-- ──────────────────────────────────────────────────────────
CREATE TABLE learning_paths (
    id                          BIGSERIAL   PRIMARY KEY,
    user_id                     UUID        NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    current_hsk_level           INTEGER     NOT NULL DEFAULT 1,
    target_hsk_level            INTEGER     NOT NULL DEFAULT 6,
    recommended_daily_words     INTEGER     NOT NULL DEFAULT 10,
    generated_at                TIMESTAMP   NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_path_hsk CHECK (
        current_hsk_level >= 1 AND
        target_hsk_level <= 9 AND
        current_hsk_level <= target_hsk_level
    )
);

-- ──────────────────────────────────────────────────────────
--  10. EXAMS TABLE
-- ──────────────────────────────────────────────────────────
CREATE TABLE exams (
    id                  BIGSERIAL       PRIMARY KEY,
    title               VARCHAR(300)    NOT NULL,
    hsk_level           INTEGER         NOT NULL,
    exam_type           VARCHAR(20)     NOT NULL,
    duration_minutes    INTEGER         NOT NULL DEFAULT 90,
    created_at          TIMESTAMP       NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_exam_type    CHECK (exam_type IN ('PLACEMENT', 'MOCK', 'PRACTICE')),
    CONSTRAINT chk_exam_hsk     CHECK (hsk_level >= 1 AND hsk_level <= 9)
);

CREATE INDEX idx_exams_type      ON exams(exam_type);
CREATE INDEX idx_exams_hsk_level ON exams(hsk_level);

-- ──────────────────────────────────────────────────────────
--  11. QUESTIONS TABLE
--      options: JSONB {"A": "...", "B": "...", "C": "...", "D": "..."}
--      correct_answer: "A" | "B" | "C" | "D" | plain text
-- ──────────────────────────────────────────────────────────
CREATE TABLE questions (
    id              BIGSERIAL       PRIMARY KEY,
    exam_id         BIGINT          NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    question_type   VARCHAR(20)     NOT NULL,
    content         TEXT            NOT NULL,
    audio_url       VARCHAR(500),
    options         JSONB           NOT NULL DEFAULT '{}',
    correct_answer  VARCHAR(10)     NOT NULL,
    hsk_level       INTEGER,

    CONSTRAINT chk_question_type CHECK (question_type IN ('MULTIPLE_CHOICE', 'FILL_BLANK', 'LISTENING'))
);

CREATE INDEX idx_questions_exam_id ON questions(exam_id);

-- ──────────────────────────────────────────────────────────
--  12. EXAM ATTEMPTS TABLE
--      answers: JSONB {"questionId": "userAnswer", ...}
-- ──────────────────────────────────────────────────────────
CREATE TABLE exam_attempts (
    id                  BIGSERIAL       PRIMARY KEY,
    user_id             UUID            NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exam_id             BIGINT          NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
    score               DECIMAL(5, 2),
    passed              BOOLEAN,
    answers             JSONB           NOT NULL DEFAULT '{}',
    started_at          TIMESTAMP       NOT NULL DEFAULT NOW(),
    finished_at         TIMESTAMP,
    time_taken_seconds  INTEGER
);

CREATE INDEX idx_exam_attempts_user_id ON exam_attempts(user_id);
CREATE INDEX idx_exam_attempts_exam_id ON exam_attempts(exam_id);

-- ──────────────────────────────────────────────────────────
--  13. SPEECH RECORDS TABLE
--      Stores result of Whisper ASR pronunciation scoring.
-- ──────────────────────────────────────────────────────────
CREATE TABLE speech_records (
    id                  BIGSERIAL       PRIMARY KEY,
    user_id             UUID            NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vocabulary_id       BIGINT          REFERENCES vocabulary(id) ON DELETE SET NULL,
    target_text         VARCHAR(500)    NOT NULL,
    audio_url           VARCHAR(500),
    whisper_transcript  VARCHAR(500),
    accuracy_score      DECIMAL(5, 2),
    recorded_at         TIMESTAMP       NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_speech_records_user_id ON speech_records(user_id);

COMMENT ON TABLE  speech_records                    IS 'Pronunciation records scored by Whisper ASR';
COMMENT ON COLUMN speech_records.whisper_transcript IS 'Raw text from Whisper model transcription';
COMMENT ON COLUMN speech_records.accuracy_score     IS '0-100 score based on transcript similarity';
